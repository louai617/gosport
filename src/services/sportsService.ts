/**
 * Sportsbook reads: sports, competitions, fixtures and results.
 *
 * DEMO: the dataset is generated in-process. Fixtures, scores and prices are
 * invented — no feed, no live scoreboard, no settlement.
 */

/**
 * Route shapes live here so a search result never has to guess one. Keep in
 * step with `src/app` if a segment is ever renamed.
 */
const routes = {
  sport: (key: SportKey) => `/sports/${key}`,
  competition: (id: string) => `/competitions/${id}`,
  event: (id: string) => `/event/${id}`,
  team: (id: string) => `/teams/${id}`,
} as const;

const RESULT_STATUSES: EventStatus[] = ["finished", "cancelled", "postponed"];

/* ------------------------------------------------------------------ catalogue */

export async function getSports(): Promise<Sport[]> {
  return [...getDataset().sports].sort((a, b) => a.order - b.order);
}

export async function getSportByKey(key: SportKey): Promise<Sport | null> {
  return getDatasetIndex(getDataset()).sportsByKey.get(key) ?? null;
}

export async function getSportById(id: string): Promise<Sport | null> {
  return getDatasetIndex(getDataset()).sportsById.get(id) ?? null;
}

export async function getCountries(): Promise<Country[]> {
  return [...getDataset().countries].sort((a, b) => a.code.localeCompare(b.code));
}

export async function getCompetitions(query: CompetitionQuery = {}): Promise<Competition[]> {
  const matched = getDataset().competitions.filter((competition) => {
    if (query.sportId && competition.sportId !== query.sportId) return false;
    if (query.countryId && competition.countryId !== query.countryId) return false;
    if (query.popular !== undefined && competition.popular !== query.popular) return false;
    return true;
  });

  matched.sort(byProminence);
  return query.limit !== undefined ? matched.slice(0, Math.max(0, query.limit)) : matched;
}

export async function getCompetitionById(id: string): Promise<Competition | null> {
  return getDatasetIndex(getDataset()).competitionsById.get(id) ?? null;
}

export async function getPopularCompetitions(limit = 8): Promise<Competition[]> {
  return getCompetitions({ popular: true, limit });
}

export async function getTeamById(id: string): Promise<Team | null> {
  return getDatasetIndex(getDataset()).teamsById.get(id) ?? null;
}

/** Flagship competitions first, then the busiest, then alphabetically. */
function byProminence(a: Competition, b: Competition): number {
  if (a.popular !== b.popular) return a.popular ? -1 : 1;
  if (b.eventCount !== a.eventCount) return b.eventCount - a.eventCount;
  return a.name.localeCompare(b.name);
}

/* --------------------------------------------------------------------- events */

/**
 * Joins an event to its sport, competition, country, teams and markets.
 *
 * Exported because the admin and account services build the same view. Throws
 * on a dangling reference: the dataset is generated by a single writer, so a
 * broken link is a generator bug that must surface loudly rather than render
 * a half-empty card.
 */
export function toEventDetail(dataset: MockDataset, event: SportEvent): EventDetail {
  const index = getDatasetIndex(dataset);
  const sport = index.sportsById.get(event.sportId);
  const competition = index.competitionsById.get(event.competitionId);
  const country = competition ? index.countriesById.get(competition.countryId) : undefined;
  const homeTeam = index.teamsById.get(event.homeTeamId);
  const awayTeam = index.teamsById.get(event.awayTeamId);

  if (!sport || !competition || !country || !homeTeam || !awayTeam) {
    throw new Error(`Event ${event.id} references a record that is not in the dataset.`);
  }

  return {
    ...event,
    sport,
    competition,
    country,
    homeTeam,
    awayTeam,
    markets: toMarketsWithSelections(dataset, event.id),
  };
}

export async function getEvents(query: EventQuery = {}): Promise<EventDetail[]> {
  const dataset = getDataset();
  return selectEvents(dataset, query).map((event) => toEventDetail(dataset, event));
}

export async function getEventById(id: string): Promise<EventDetail | null> {
  const dataset = getDataset();
  const event = getDatasetIndex(dataset).eventsById.get(id);
  return event ? toEventDetail(dataset, event) : null;
}

export async function getLiveEvents(query: EventQuery = {}): Promise<EventDetail[]> {
  return getEvents({ ...query, status: "live" });
}

export async function getUpcomingEvents(query: EventQuery = {}): Promise<EventDetail[]> {
  const dataset = getDataset();
  return getEvents({
    ...query,
    status: "scheduled",
    fromIso: query.fromIso ?? new Date(dataset.nowMs).toISOString(),
  });
}

/** Hero fixture: a live one if there is one, otherwise the next kick-off. */
export async function getFeaturedEvent(sportKey?: SportKey): Promise<EventDetail | null> {
  const candidates = await getEvents({
    sportKey,
    featured: true,
    status: ["live", "scheduled"],
  });
  return candidates.find((event) => event.status === "live") ?? candidates[0] ?? null;
}

/** Fixture list grouped the way the sportsbook renders it: one block per competition. */
export async function getCompetitionsWithEvents(
  query: EventQuery = {},
): Promise<CompetitionWithEvents[]> {
  const events = await getEvents(query);

  const blocks = new Map<string, CompetitionWithEvents>();
  for (const event of events) {
    const existing = blocks.get(event.competitionId);
    if (existing) existing.events.push(event);
    else {
      blocks.set(event.competitionId, {
        competition: event.competition,
        country: event.country,
        events: [event],
      });
    }
  }

  return [...blocks.values()].sort((a, b) => {
    if (a.competition.popular !== b.competition.popular) {
      return a.competition.popular ? -1 : 1;
    }
    if (b.events.length !== a.events.length) return b.events.length - a.events.length;
    return a.competition.name.localeCompare(b.competition.name);
  });
}

export async function getResults(
  query: EventQuery & { dateIso?: string } = {},
): Promise<Paginated<EventResult>> {
  const dataset = getDataset();
  const { dateIso, page, pageSize, limit, status, ...rest } = query;

  const statuses = asArray(status);
  const finished = selectEvents(dataset, {
    ...rest,
    status: statuses.length > 0 ? statuses : RESULT_STATUSES,
  });

  const day = dateIso ? appDayKey(dateIso) : undefined;
  const onDay = day ? finished.filter((event) => appDayKey(event.startTime) === day) : finished;

  // Results read newest-first, the reverse of a fixture list.
  onDay.sort((a, b) => Date.parse(b.startTime) - Date.parse(a.startTime));

  const results: EventResult[] = onDay.map((event) => ({
    event: toEventDetail(dataset, event),
    outcomeKey: outcomeKeyFor(event),
  }));

  return paginate(results, page, pageSize ?? limit);
}

function outcomeKeyFor(event: SportEvent): string {
  if (event.status === "cancelled") return "results.cancelled";
  if (event.status === "postponed") return "results.postponed";
  return "results.fullTime";
}

function selectEvents(dataset: MockDataset, query: EventQuery): SportEvent[] {
  const index = getDatasetIndex(dataset);
  const statuses = asArray(query.status);

  let sportId = query.sportId;
  if (query.sportKey) {
    const sport = index.sportsByKey.get(query.sportKey);
    // An unknown key is a filter that matches nothing, not an absent filter.
    if (!sport) return [];
    sportId = sport.id;
  }

  const fromMs = query.fromIso ? Date.parse(query.fromIso) : undefined;
  const toMs = query.toIso ? Date.parse(query.toIso) : undefined;

  const matched = dataset.events.filter((event) => {
    if (sportId && event.sportId !== sportId) return false;
    if (query.competitionId && event.competitionId !== query.competitionId) return false;
    if (query.countryId) {
      const competition = index.competitionsById.get(event.competitionId);
      if (!competition || competition.countryId !== query.countryId) return false;
    }
    if (statuses.length > 0 && !statuses.includes(event.status)) return false;
    if (query.featured !== undefined && event.featured !== query.featured) return false;

    const startMs = Date.parse(event.startTime);
    if (fromMs !== undefined && startMs < fromMs) return false;
    if (toMs !== undefined && startMs > toMs) return false;
    return true;
  });

  matched.sort(byKickOff);
  return applyWindow(matched, query);
}

/** Ascending kick-off, id as tie-break so ordering is stable across renders. */
function byKickOff(a: SportEvent, b: SportEvent): number {
  const delta = Date.parse(a.startTime) - Date.parse(b.startTime);
  return delta !== 0 ? delta : a.id.localeCompare(b.id);
}

function applyWindow<T>(
  items: T[],
  window: { limit?: number; page?: number; pageSize?: number },
): T[] {
  if (window.page !== undefined || window.pageSize !== undefined) {
    return paginate(items, window.page, window.pageSize).items;
  }
  return window.limit !== undefined ? items.slice(0, Math.max(0, window.limit)) : items;
}

/* --------------------------------------------------------------------- search */

/** Below this a query matches almost everything, which is worse than no result. */
const MIN_QUERY_LENGTH = 2;

/**
 * Relevance is `strength * 10 + kind weight`: how well the text matched always
 * outranks what kind of thing matched, and a fixture beats the competition or
 * team it belongs to because it is the actionable result.
 */
const KIND_WEIGHT = { event: 4, competition: 3, team: 2, sport: 1 } as const;

type MatchStrength = 0 | 1 | 2 | 3;

function matchStrength(haystack: string, needle: string): MatchStrength {
  const folded = normalise(haystack);
  if (folded === needle) return 3;
  if (folded.startsWith(needle)) return 2;
  if (folded.includes(needle)) return 1;
  return 0;
}

/** Best match across several fields — a team code hit counts as much as a name hit. */
function bestStrength(fields: string[], needle: string): MatchStrength {
  let best: MatchStrength = 0;
  for (const field of fields) {
    const strength = matchStrength(field, needle);
    if (strength > best) best = strength;
    if (best === 3) break;
  }
  return best;
}

export async function search(query: string, limit = 8): Promise<SearchResponse> {
  const needle = normalise(query);
  if (needle.length < MIN_QUERY_LENGTH) return { query, results: [], total: 0 };

  const dataset = getDataset();
  const index = getDatasetIndex(dataset);
  const scored: Array<{ score: number; result: SearchResult }> = [];

  const push = (strength: MatchStrength, kind: SearchResult["kind"], result: SearchResult) => {
    if (strength === 0) return;
    scored.push({ score: strength * 10 + KIND_WEIGHT[kind], result });
  };

  for (const sport of dataset.sports) {
    // Sports have no display name in the feed, so the canonical key is what is
    // matched; the translated label is resolved at render time.
    push(bestStrength([sport.key], needle), "sport", {
      kind: "sport",
      id: sport.id,
      title: sport.nameKey,
      href: routes.sport(sport.key),
    });
  }

  for (const competition of dataset.competitions) {
    const country = index.countriesById.get(competition.countryId);
    push(bestStrength([competition.name, competition.shortName], needle), "competition", {
      kind: "competition",
      id: competition.id,
      title: competition.name,
      subtitleKey: country?.nameKey,
      href: routes.competition(competition.id),
    });
  }

  for (const team of dataset.teams) {
    const country = index.countriesById.get(team.countryId);
    push(bestStrength([team.name, team.shortName, team.code], needle), "team", {
      kind: "team",
      id: team.id,
      title: team.name,
      subtitleKey: country?.nameKey,
      href: routes.team(team.id),
    });
  }

  for (const event of dataset.events) {
    if (event.status === "cancelled") continue;
    const homeTeam = index.teamsById.get(event.homeTeamId);
    const awayTeam = index.teamsById.get(event.awayTeamId);
    const competition = index.competitionsById.get(event.competitionId);
    if (!homeTeam || !awayTeam || !competition) continue;

    const title = `${homeTeam.name} — ${awayTeam.name}`;
    push(bestStrength([title, homeTeam.name, awayTeam.name], needle), "event", {
      kind: "event",
      id: event.id,
      title,
      subtitle: competition.name,
      href: routes.event(event.id),
      meta: event.startTime,
    });
  }

  scored.sort((a, b) => {
    if (b.score !== a.score) return b.score - a.score;
    return a.result.title.localeCompare(b.result.title);
  });

  return {
    query,
    results: scored.slice(0, Math.max(0, limit)).map((entry) => entry.result),
    total: scored.length,
  };
}
