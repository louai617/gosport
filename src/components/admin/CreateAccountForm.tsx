"use client";

import Link from "next/link";
import { useState } from "react";
import { createManagerAction, createPlayerAction } from "@/app/actions/admin";
import { useFormAction } from "@/lib/useFormAction";
import { useT } from "@/i18n/I18nProvider";
import { newIdempotencyKey } from "@/components/wallet/WalletProvider";
import { Alert } from "@/components/ui/Alert";
import { Button, buttonStyles } from "@/components/ui/Button";
import { Input } from "@/components/ui/Input";
import { CredentialsReveal } from "./CredentialsReveal";

export interface CreateAccountFormProps {
  kind: "player" | "manager";
  /** Whether the actor can put credit on the new account at creation. */
  creditEnabled: boolean;
  /** The manager's own balance, shown beside the credit field. */
  balanceLabel?: string;
}

/**
 * Creating an account is one step: an optional label, an optional handle, an
 * optional opening credit — and a button. The username and password are
 * generated by the server and come back once, in the box below the form.
 */
export function CreateAccountForm({ kind, creditEnabled, balanceLabel }: CreateAccountFormProps) {
  const t = useT();
  const { state, pending, formProps } = useFormAction(
    kind === "player" ? createPlayerAction : createManagerAction,
  );
  const [key, setKey] = useState(() => newIdempotencyKey());

  const fieldError = (name: string) =>
    state.fieldErrors?.[name] ? t(state.fieldErrors[name]) : undefined;

  if (state.ok && state.data?.password) {
    const base = kind === "player" ? "/admin/players" : "/admin/managers";
    return (
      <div className="space-y-4">
        <Alert tone="success" title={t(kind === "player" ? "admin.players.created" : "admin.managers.created")}>
          {state.data.credited
            ? t("admin.accounts.createdWithCredit", { amount: Number(state.data.credited).toFixed(2) })
            : t("admin.accounts.createdBody")}
        </Alert>

        <CredentialsReveal username={String(state.data.username)} password={String(state.data.password)} />

        <div className="flex flex-wrap gap-2">
          <Link href={`${base}/${state.data.accountId}`} className={buttonStyles()}>
            {t(kind === "player" ? "admin.players.openProfile" : "admin.managers.openProfile")}
          </Link>
          <Link
            href={`${base}/new`}
            onClick={() => setKey(newIdempotencyKey())}
            className={buttonStyles({ variant: "secondary" })}
          >
            {t(kind === "player" ? "admin.players.createAnother" : "admin.managers.createAnother")}
          </Link>
        </div>
      </div>
    );
  }

  return (
    <form {...formProps} className="space-y-5 rounded-xl border border-line bg-surface p-5" noValidate>
      {state.messageKey && !state.ok ? <Alert tone="danger">{t(state.messageKey)}</Alert> : null}
      <input type="hidden" name="idempotencyKey" value={key} />

      <div className="grid gap-4 sm:grid-cols-2">
        <Input
          name="displayName"
          label={`${t("admin.accounts.displayName")} (${t("ui.optional")})`}
          hint={t("admin.accounts.displayNameHint")}
          error={fieldError("displayName")}
        />
        <Input
          name="username"
          autoCapitalize="none"
          spellCheck={false}
          label={`${t("auth.field.username")} (${t("ui.optional")})`}
          hint={t("admin.accounts.usernameHint")}
          error={fieldError("username")}
        />
        {creditEnabled ? (
          <Input
            name="initialCredit"
            inputMode="decimal"
            label={`${t("admin.accounts.initialCredit")} (${t("ui.optional")})`}
            hint={balanceLabel ? t("admin.accounts.initialCreditFromBalance", { balance: balanceLabel }) : t("admin.accounts.initialCreditHint")}
            error={fieldError("initialCredit")}
          />
        ) : null}
      </div>

      <p className="text-small text-ink-muted">{t("admin.accounts.generatedNote")}</p>

      <Button type="submit" size="lg" loading={pending}>
        {t(kind === "player" ? "admin.players.create" : "admin.managers.create")}
      </Button>
    </form>
  );
}
